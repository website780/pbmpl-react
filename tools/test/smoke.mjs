import {chromium} from 'playwright-core';
import http from 'http'; import fs from 'fs'; import path from 'path';
const root=process.argv[2], urlp=process.argv[3]||'/';
const mime={'.html':'text/html','.js':'text/javascript','.css':'text/css','.png':'image/png','.jpg':'image/jpeg','.svg':'image/svg+xml','.woff2':'font/woff2','.woff':'font/woff','.json':'application/json','.webp':'image/webp','.gif':'image/gif','.ico':'image/x-icon','.ttf':'font/ttf'};
const srv=http.createServer((q,s)=>{let p=decodeURIComponent(q.url.split('?')[0]);let f=path.join(root,p);if(fs.existsSync(f)&&fs.statSync(f).isDirectory())f=path.join(f,'index.html');if(!fs.existsSync(f)){s.statusCode=404;return s.end('nf');}s.setHeader('content-type',mime[path.extname(f)]||'application/octet-stream');fs.createReadStream(f).pipe(s);}).listen(0);
const port=srv.address().port;
const b=await chromium.launch({executablePath:'/opt/pw-browsers/chromium'});
const pg=await b.newPage({viewport:{width:1440,height:900}});
const errs=[],nf=[];
pg.on('pageerror',e=>errs.push(e.message));
pg.on('console',m=>m.type()==='error'&&errs.push('console:'+m.text()));
pg.on('response',r=>r.status()>=400&&nf.push(r.status()+' '+r.url()));
pg.on('requestfailed',r=>nf.push('FAIL '+r.url()));
await pg.goto(`http://localhost:${port}${urlp}`,{waitUntil:'networkidle'});
await pg.waitForTimeout(2500);
await pg.screenshot({path:'/home/claude/work/test/'+(process.argv[4]||'home_react')+'.png'});
console.log('title',await pg.title(),'h',await pg.evaluate(()=>document.body.scrollHeight));
console.log('errors',errs.slice(0,15));console.log('404s',nf.slice(0,20));
await b.close();srv.close();
